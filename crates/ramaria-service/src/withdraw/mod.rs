//! crates/ramaria-service/src/withdraw/mod.rs - Ramaria 消息撤回域
//!
//! 设计特点:
//! - 两路入口：通道撤回通知（定位绑定与会话消息 → 幂等标记 → 回应生成）与本地撤回
//!   （仅本地会话本人消息，窗口内标记）
//! - 回应用按即时事件触发：豁免宽限 / 退避 / 最小空闲，只走打扰控制子集闸门
//! - 连撤在途去重：同一会话首条处理完成前，后续撤回通知不再触发回应
//! - 撤回文本两态渲染：已被消费（其后有助手消息）保留原内容并追加信号；未消费
//!   仅保留信号
//! - 隐私：日志不携带消息内容与外部标识原文

mod local;
mod notice;

#[cfg(test)]
mod tests;

pub(crate) use local::recall_local_message;
pub(crate) use notice::handle_notice;

// =========================================================
// 常量
// =========================================================

/// 撤回反应窗口（毫秒）：撤回发生到处理之间的最长允许延迟，超出不触发回应。
pub(crate) const RECALL_REACTION_WINDOW_MS: i64 = 120_000;

/// 撤回信号文本（渲染进历史窗口的替换 / 追加内容）。
pub(crate) const RECALL_SIGNAL: &str = "〔对方撤回了一条消息〕";

// =========================================================
// 撤回文本渲染
// =========================================================

/// 渲染被撤回消息在历史窗口中的正文。
///
/// 语义:
/// - 已消费（撤回消息之后已有助手消息）：原内容保留并追加撤回信号；
/// - 未消费：仅保留撤回信号（原内容已被撤回，不进入 Prompt）。
///
/// 参数:
/// - `content`: 已渲染（图片占位符替换后）的正文；
/// - `consumed`: 撤回消息是否已被消费。
///
/// 返回:
/// - 替换后的正文（纯函数）。
pub(crate) fn render_recalled_content(content: &str, consumed: bool) -> String {
    if consumed {
        format!("{content}{RECALL_SIGNAL}")
    } else {
        RECALL_SIGNAL.to_string()
    }
}
