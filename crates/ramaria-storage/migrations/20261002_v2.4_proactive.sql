-- =========================================================
-- 主动消息标记列（messages.is_proactive）
-- =========================================================
-- 目的:
-- - messages 表追加 is_proactive，标记由主动对话路径生成的消息；
--   存量行自动回填 0（常规消息口径），既有库零改动。
--
-- 约定:
-- - 只增不删：不修改既有列、不重建表；新增列均向后兼容。
-- - 与 source 语义无关（source 仍表示本地/线上 provider）：本列只标记产生方式，
--   记忆回流不按消息来源过滤，故不加索引。
--
-- 字段约定:
-- - 0 = 常规消息（用户输入与被动回复），1 = 主动生成消息。

ALTER TABLE messages ADD COLUMN is_proactive INTEGER NOT NULL DEFAULT 0;
